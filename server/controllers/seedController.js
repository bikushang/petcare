async function ensureStaffSeeded(extraData = []) {
  const existing = new Set(
    (await Staff.find({}, "email -_id").lean()).map((staff) =>
      staff.email.toLowerCase(),
    ),
  );
  const missing = staffSeed
    .map((staff, index) => ({ staff, index }))
    .filter(({ staff }) => !existing.has(staff.email.toLowerCase()))
    .map(({ staff, index }) => ({
      _id: uid(),
      name: staff.name,
      role: staff.role,
      branch: staff.branch,
      branchAccess: staff.branchAccess,
      phone: staff.phone,
      email: staff.email,
      password: hash(staff.password),
      status: staff.status,
      shift: staff.shift,
      ...(extraData[index] || {}),
    }));

  if (missing.length > 0) await Staff.insertMany(missing);
  return missing.length;
}

